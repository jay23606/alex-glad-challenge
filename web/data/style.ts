// Контент страницы /style («Антоновайзер»). Клиент-safe: только текстовые
// константы, без server-only и core (инвариант client-островов).
//
// Продуктовая модель — две независимые оси:
//   тон    — как автор говорит с читателем (утешить / по-свойски / разнести);
//   формат — какую структуру получит текст (разбор / эссе / инструкция / антипаника).
// Примеры — готовые истории: клик подставляет исходник и обе настройки, поэтому
// продукт объясняется сам, без легенды из абстрактных «мягко/жёстко».

export type StyleTone = 'soft' | 'normal' | 'hard';
export type StyleFormat = 'auto' | 'post' | 'essay' | 'guide' | 'calm';
export type StyleLlm = 'cloud' | 'local';

export interface StyleExample {
  /** Человеческая история: что случилось (заголовок карточки). */
  title: string;
  /** Настроение, которое пользователь хочет передать. */
  mood: string;
  /** Исходный текст, подставляемый в textarea. */
  text: string;
  /** Тон и формат, которые раскрывают историю. */
  tone: StyleTone;
  format: StyleFormat;
  signature: boolean;
  /** Что получится на выходе — короткая подпись на карточке. */
  outcome: string;
}

export interface StyleToneOption {
  id: StyleTone;
  label: string;
  tagline: string;
  description: string;
}

export interface StyleFormatOption {
  id: StyleFormat;
  label: string;
  tagline: string;
  description: string;
}

export interface StyleEngineOption {
  id: StyleLlm;
  label: string;
  hint: string;
}

