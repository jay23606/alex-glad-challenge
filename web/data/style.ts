/** Человеческая подпись тона — для результата, истории студии и карточек. */
export function styleToneLabel(id: StyleTone): string {
  return styleTones.find((tone) => tone.id === id)?.label ?? id;
}

/** Человеческая подпись формата — для результата, истории студии и карточек. */
export function styleFormatLabel(id: StyleFormat): string {
  return styleFormats.find((format) => format.id === id)?.label ?? id;
}

