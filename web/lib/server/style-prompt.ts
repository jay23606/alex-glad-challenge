/** User-сообщение агента потока: рамка (автор/источник), картинки, режим, исходник. */
export function buildThreadUserPrompt(input: AntonovThreadInput): string {
  const author = input.author.length > 0 ? input.author : '(не указан — пиши «автор разбора», без выдуманного имени)';
  const source = input.source.length > 0 ? input.source : '(не указан)';
  const images =
    input.images.length > 0
      ? `Картинки для раскладки (каждую — маркером [📸: …] ровно один раз):\n${input.images
          .map((img, i) => `${i + 1}. ${img}`)
          .join('\n')}`
      : 'Картинок нет — маркеры [📸: …] не использовать.';
  return `Автор оригинала: ${author}
Источник: ${source}
Тон переводчика: ${MODE_LABEL[input.mode]}.
${images}

ТЕКСТ ОРИГИНАЛА:
${input.text}`;
}
